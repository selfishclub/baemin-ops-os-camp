import { describe, expect, it } from "vitest";
import { parseBaeminStatement } from "./deliveryStatement";

// 배민 정산명세서 "상세" 시트 축소판 (가짜 숫자). 머리줄 3줄, 마지막 열이 (H) 입금금액
const H1 = ["입금일", "정산대상기간", "입금 금액", "이용서비스", "주문유형/기타", "(A) 주문중개", "(A) 주문중개", "(A) 주문중개", "(B) 배달", "(C) 그외", "(E) 부가세", "(H) 입금금액"];
const H2 = ["입금일", "정산대상기간", "입금 금액", "이용서비스", "주문유형/기타", "주문금액", "주문금액", "중개이용료", "가게배달팁", "결제정산수수료", "(E) 부가세", "(H) 입금금액"];
const H3 = ["입금일", "정산대상기간", "입금 금액", "이용서비스", "주문유형/기타", "바로결제주문금액", "만나서결제주문금액", "알뜰배달 중개이용료", "바로결제배달팁", "기본수수료(정률)", "(E) 부가세", "(H) 입금금액"];
const grid = [
  ["정산 상세내역"],
  ["거래기간: 2026-09-01 ~ 2026-09-03"],
  H1,
  H2,
  H3,
  ["2026-09-04", "2026-09-01", 84305, "음식배달", "알뜰·한집배달", 110000, 0, -7480, 0, -3300, -2335, 84305],
  ["2026-09-04", "2026-09-01", 30335, "음식배달", "배민포장주문", 34000, 0, -2312, 0, -1020, -333, 30335],
  ["2026-09-05", "2026-09-02", -2169, "음식배달", "가게배달", 0, 29000, -1972, 0, 0, -197, -2169], // 만나서결제: 가게에서 받은 돈, 수수료만 빠짐 (배달팁도 만나서 받음)
  ["2026-09-08", "2026-09-03", 0, "음식배달", "알뜰·한집배달", 58000, 0, -3944, 0, -1740, -1358, 0], // 아직 미입금
];

describe("parseBaeminStatement", () => {
  const p = parseBaeminStatement({ 요약: [["요약"]], 상세: grid as never[][] });
  it("매출일별 앱 결제 주문금액과 입금액을 모은다", () => {
    expect(p.channel).toBe("baemin");
    expect(p.from).toBe("2026-09-01");
    expect(p.to).toBe("2026-09-03");
    expect(p.days[0]).toMatchObject({ date: "2026-09-01", orders: 144000, deposit: 114640, depositDate: "2026-09-04" });
  });
  it("만나서결제는 매출에 안 넣고 참고로만 둔다", () => {
    expect(p.days[1]).toMatchObject({ date: "2026-09-02", orders: 0, deposit: -2169, meetPay: 29000 });
    expect(p.meetPay).toBe(29000);
  });
  it("수수료율은 입금 완료된 날만으로, 입금일까지 영업일 수도 낸다", () => {
    expect(p.feeRate).toBe(20.4); // (144000-114640)/144000
    expect(p.leadDays).toEqual([3]); // 9/1(화) → 9/4(금)
    expect(p.orders).toBe(202000);
  });
  it("엉뚱한 파일이면 안내", () => {
    expect(() => parseBaeminStatement({ Sheet1: [["날짜", "금액"]] } as never)).toThrow(/정산명세서/);
  });
});
